export function suggestRequestTitle(description: string) {
  const trimmed = description.trim();
  const firstSentence =
    trimmed.split(/\r?\n|[.!?]\s|[。！？]/u)[0]?.trim() || trimmed;
  const characters = Array.from(firstSentence.replace(/[.!?]$/u, ""));
  return characters.length > 80
    ? `${characters.slice(0, 79).join("").trimEnd()}…`
    : characters.join("");
}

